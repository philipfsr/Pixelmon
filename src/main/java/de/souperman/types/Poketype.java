    public String getPokedexNrString() {
        String pkdx = "0000";
        String nmbr = Integer.toString(pokedex);
        if (nmbr.length() > 4) {
            return nmbr;
        }

        pkdx = pkdx.substring(nmbr.length());

        return pkdx.concat(nmbr);
    }

